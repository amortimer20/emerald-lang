//! The C emitter (docs/compiler-design-plan.md, decision 1): the IR as one C
//! file for `zig cc`, against the runtime's interface in `emerald.h`.
//!
//! It only translates. `Int`, `Float` and `Bool` are C's `int64_t`, `double`
//! and `bool` (decision 5), and a `String` is the runtime's `em_text`. Each
//! function returns a status, 0 or 1, with its result through a pointer
//! (decision 7), and a call that fails adds itself to the trace and returns 1
//! in turn. Every way out of a function passes its exit label, which releases
//! the strings its locals hold (the IR's ownership rule, `Ir.zig`). The common case of each operation is plain
//! C, as `zig cc` can optimize it, and the runtime is called for the rest.
//!
//! `#line` directives name the Emerald file and line, so a C compiler's own
//! messages and a debugger point there. A failure's location, quoted line and
//! carets are rendered here, at build time, by `Diagnostic`, the code that
//! renders the interpreter's errors, and stored in the program as constants.

const std = @import("std");
const Source = @import("../Source.zig");
const Diagnostic = @import("../Diagnostic.zig");
const Ir = @import("Ir.zig");

const Writer = std.Io.Writer;

/// Writes `program`, compiled from `source`, as C.
pub fn emit(gpa: std.mem.Allocator, program: Ir.Program, source: *const Source, out: *Writer) (Writer.Error || std.mem.Allocator.Error)!void {
    try out.writeAll(
        \\/* Generated by `emerald build`. Edit the Emerald program instead. */
        \\#include "emerald.h"
        \\
        \\/* A failure: the function returns 1 through its exit, which releases
        \\ * what its locals hold. */
        \\#define EM_FAIL do { em_status = 1; goto em_exit; } while (0)
        \\
        \\
    );
    for (program.literals, 0..) |_, index| try out.print("static em_text *em_literal_{d};\n", .{index});

    // Where each failure and call is reported.
    for (program.sites, 0..) |span, index| {
        const rendered = try renderSite(gpa, source, span);
        defer gpa.free(rendered.text);
        try out.print("static const em_site em_site_{d} = {{ ", .{index});
        try writeString(out, rendered.location);
        try out.writeAll(", ");
        try writeString(out, rendered.snippet);
        try out.writeAll(" };\n");
    }
    // The frame each call adds to a trace: the function called, and where.
    for (program.functions) |function| for (function.blocks) |block| for (block.instructions) |one| {
        if (one.data != .call) continue;
        const called = one.data.call;
        const at = source.location(program.sites[called.site].start);
        try out.print("static const em_frame em_frame_{d} = {{ ", .{called.site});
        try writeString(out, program.functions[called.function].name);
        try out.writeAll(", ");
        var location: std.Io.Writer.Allocating = .init(gpa);
        defer location.deinit();
        try location.writer.print("{s}:{d}:{d}", .{ source.path, at.line, at.column });
        try writeString(out, location.written());
        try out.writeAll(", true };\n");
    };
    try out.writeAll("\n");

    for (program.globals, 0..) |global, index| {
        try out.print("static {s} em_global_{d}; /* {s} */\n", .{ cType(global.type), index, global.name });
    }
    try out.writeAll("\n");

    for (program.functions, 0..) |function, index| {
        try signature(out, function, index);
        try out.writeAll(";\n");
    }
    try out.writeAll("\n");

    for (program.functions, 0..) |function, index| {
        var emitter: FunctionEmitter = .{ .out = out, .program = program, .function = function, .source = source };
        try emitter.body(index);
    }

    try out.writeAll(
        \\int main(void) {
        \\    em_start();
        \\    return em_finish(em_function_0());
        \\}
        \\
    );
}

fn cType(type_: Ir.Type) []const u8 {
    return switch (type_) {
        .int => "int64_t",
        .float => "double",
        .bool => "bool",
        .string => "em_text *",
        .list => "em_list *",
        .nothing => "void",
    };
}

/// The runtime's functions that retain and release a heap value of `type_`.
fn retainName(type_: Ir.Type) []const u8 {
    return if (type_ == .list) "em_retain_list" else "em_retain";
}

fn releaseName(type_: Ir.Type) []const u8 {
    return if (type_ == .list) "em_release_list" else "em_release";
}

/// The tag and the `em_value` field for a value of `type_`.
fn kindName(type_: Ir.Type) []const u8 {
    return switch (type_) {
        .nothing => "EM_KIND_NOTHING",
        .int => "EM_KIND_INT",
        .float => "EM_KIND_FLOAT",
        .bool => "EM_KIND_BOOL",
        .string => "EM_KIND_STRING",
        .list => "EM_KIND_LIST",
    };
}

fn fieldName(type_: Ir.Type) []const u8 {
    return switch (type_) {
        .int => "integer",
        .float => "number",
        .bool => "boolean",
        .string => "text",
        .list => "list",
        .nothing => unreachable, // no `nothing` crosses as a value
    };
}

fn signature(out: *Writer, function: Ir.Function, index: usize) Writer.Error!void {
    try out.print("static int em_function_{d}(", .{index});
    var first = true;
    for (function.locals[0..function.parameter_count], 0..) |parameter, position| {
        if (!first) try out.writeAll(", ");
        first = false;
        try out.print("{s} em_local_{d}", .{ cType(parameter.type), position });
    }
    if (function.result != .nothing) {
        if (!first) try out.writeAll(", ");
        first = false;
        try out.print("{s} *em_result", .{cType(function.result)});
    }
    if (first) try out.writeAll("void");
    try out.writeAll(")");
}

const Rendered = struct {
    text: []u8,
    location: []const u8,
    snippet: []const u8,
};

/// `path:line:column` and the quoted line with its carets, cut from a
/// diagnostic rendered with an empty message and help.
fn renderSite(gpa: std.mem.Allocator, source: *const Source, span: Source.Span) std.mem.Allocator.Error!Rendered {
    const diagnostic: Diagnostic = .{ .span = span, .message = "", .help = "" };
    const text = try diagnostic.renderAlloc(gpa, &.{source.*});
    // "path:line:column: \n  line\n  ^^^\n\n"
    const first_end = std.mem.indexOfScalar(u8, text, '\n').?;
    const snippet_end = std.mem.indexOfScalarPos(u8, text, std.mem.indexOfScalarPos(u8, text, first_end + 1, '\n').? + 1, '\n').? + 1;
    return .{
        .text = text,
        .location = text[0 .. first_end - 2],
        .snippet = text[first_end + 1 .. snippet_end],
    };
}

/// A C string literal holding `bytes` exactly. Anything but plain printable
/// ASCII is an octal escape, so the file stays ASCII whatever the program's
/// text holds.
fn writeString(out: *Writer, bytes: []const u8) Writer.Error!void {
    try out.writeByte('"');
    for (bytes) |byte| {
        if (byte >= 0x20 and byte < 0x7f and byte != '"' and byte != '\\' and byte != '?') {
            try out.writeByte(byte);
        } else {
            try out.print("\\{o:0>3}", .{byte});
        }
    }
    try out.writeByte('"');
}

const FunctionEmitter = struct {
    out: *Writer,
    program: Ir.Program,
    function: Ir.Function,
    source: *const Source,
    line: u32 = 0,

    fn body(self: *FunctionEmitter, index: usize) Writer.Error!void {
        const out = self.out;
        if (self.function.name.len != 0) try out.print("/* {s} */\n", .{self.function.name});
        try signature(out, self.function, index);
        try out.writeAll(" {\n    int em_status = 0;\n");
        // A parameter is borrowed from the caller; retaining it lets the exit
        // release every local alike.
        for (self.function.locals[0..self.function.parameter_count], 0..) |parameter, position| {
            if (parameter.type.counted()) try out.print("    {s}(em_local_{d});\n", .{ retainName(parameter.type), position });
        }
        for (self.function.locals[self.function.parameter_count..], self.function.parameter_count..) |local, position| {
            // Zeroed, so C never reads an indeterminate value; the checker
            // has proved the program assigns each before it reads it.
            try out.print("    {s} em_local_{d} = 0;", .{ cType(local.type), position });
            if (local.name.len != 0) try out.print(" /* {s} */", .{local.name});
            try out.writeAll("\n");
        }
        for (self.function.blocks, 0..) |block, block_index| {
            try out.print("em_block_{d}:;\n", .{block_index});
            for (block.instructions) |one| try self.instruction(one);
            try self.terminator(block.terminator);
        }
        try out.writeAll("em_exit:;\n");
        for (self.function.locals, 0..) |local, position| {
            if (local.type.counted()) try out.print("    {s}(em_local_{d});\n", .{ releaseName(local.type), position });
        }
        try out.writeAll("    return em_status;\n}\n\n");
    }

    fn lineMark(self: *FunctionEmitter, line: u32) Writer.Error!void {
        if (line == self.line) return;
        self.line = line;
        try self.out.print("#line {d} ", .{line});
        try writeString(self.out, self.source.path);
        try self.out.writeAll("\n");
    }

    fn operand(self: *FunctionEmitter, value: Ir.Operand) Writer.Error!void {
        const out = self.out;
        switch (value) {
            .local => |local| try out.print("em_local_{d}", .{local}),
            .global => |global| try out.print("em_global_{d}", .{global}),
            .int => |number| if (number == std.math.minInt(i64))
                try out.writeAll("INT64_MIN")
            else
                try out.print("INT64_C({d})", .{number}),
            // A hexadecimal literal is exact, where decimal would round.
            .float => |number| try out.print("{x}", .{number}),
            .bool => |truth| try out.writeAll(if (truth) "true" else "false"),
            .literal => |index| {
                const text = self.program.literals[index];
                try out.print("em_literal(&em_literal_{d}, ", .{index});
                try writeString(out, text);
                try out.print(", {d})", .{text.len});
            },
        }
    }

    fn placeType(self: *FunctionEmitter, at: Ir.Place) Ir.Type {
        return switch (at) {
            .local => |local| self.function.locals[local].type,
            .global => |global| self.program.globals[global].type,
        };
    }

    /// Stores a new reference, `t` in the C, into `destination`, releasing
    /// what it held.
    fn takeInto(self: *FunctionEmitter, destination: Ir.Place) Writer.Error!void {
        try self.out.print(" {s}(", .{releaseName(self.placeType(destination))});
        try self.place(destination);
        try self.out.writeAll("); ");
        try self.place(destination);
        try self.out.writeAll(" = t;");
    }

    fn place(self: *FunctionEmitter, at: Ir.Place) Writer.Error!void {
        try self.operand(switch (at) {
            .local => |local| .{ .local = local },
            .global => |global| .{ .global = global },
        });
    }

    /// `    format`, with each `@` replaced by the next of `parts`.
    fn line_(self: *FunctionEmitter, comptime format: []const u8, parts: anytype) Writer.Error!void {
        try self.out.writeAll("    ");
        comptime var part = 0;
        inline for (format) |character| {
            if (character == '@') {
                const value = parts[part];
                switch (@TypeOf(value)) {
                    Ir.Operand => try self.operand(value),
                    Ir.Place => try self.place(value),
                    else => try self.out.print("{s}", .{value}),
                }
                part += 1;
            } else try self.out.writeByte(character);
        }
        try self.out.writeAll("\n");
    }

    fn siteName(buffer: []u8, site: Ir.Site) []const u8 {
        return std.fmt.bufPrint(buffer, "&em_site_{d}", .{site}) catch unreachable;
    }

    fn instruction(self: *FunctionEmitter, one: Ir.Instruction) Writer.Error!void {
        try self.lineMark(one.line);
        var site_buffer: [32]u8 = undefined;
        switch (one.data) {
            .move => |move| if (self.placeType(move.destination).counted())
                try self.line_("{ @t = @; @(t); @(@); @ = t; }", .{ cType(self.placeType(move.destination)), move.source, retainName(self.placeType(move.destination)), releaseName(self.placeType(move.destination)), move.destination, move.destination })
            else
                try self.line_("@ = @;", .{ move.destination, move.source }),
            .int_arithmetic => |arithmetic| {
                const site = siteName(&site_buffer, arithmetic.site);
                const op = operatorName(arithmetic.operator);
                switch (arithmetic.operator) {
                    .add, .subtract, .multiply => {
                        const builtin_name = switch (arithmetic.operator) {
                            .add => "__builtin_add_overflow",
                            .subtract => "__builtin_sub_overflow",
                            else => "__builtin_mul_overflow",
                        };
                        // Into a temporary: an overflowing builtin still writes,
                        // and the destination may be an operand.
                        try self.line_("{ int64_t t; if (@(@, @, &t)) { em_int_arithmetic(@, @, @, &t, @); EM_FAIL; } @ = t; }", .{ builtin_name, arithmetic.left, arithmetic.right, op, arithmetic.left, arithmetic.right, site, arithmetic.destination });
                    },
                    .floor_divide => try self.line_("if (@ == 0 || (@ == INT64_MIN && @ == -1)) { int64_t t; em_int_arithmetic(@, @, @, &t, @); EM_FAIL; } @ = em_floor_divide(@, @);", .{ arithmetic.right, arithmetic.left, arithmetic.right, op, arithmetic.left, arithmetic.right, site, arithmetic.destination, arithmetic.left, arithmetic.right }),
                    .remainder => try self.line_("if (@ == 0) { int64_t t; em_int_arithmetic(@, @, @, &t, @); EM_FAIL; } @ = em_remainder(@, @);", .{ arithmetic.right, op, arithmetic.left, arithmetic.right, site, arithmetic.destination, arithmetic.left, arithmetic.right }),
                    .power => try self.line_("{ int64_t t; if (em_int_arithmetic(@, @, @, &t, @)) EM_FAIL; @ = t; }", .{ op, arithmetic.left, arithmetic.right, site, arithmetic.destination }),
                    .divide => unreachable, // a Float operation
                }
            },
            .float_arithmetic => |arithmetic| {
                const site = siteName(&site_buffer, arithmetic.site);
                const op = operatorName(arithmetic.operator);
                switch (arithmetic.operator) {
                    .add => try self.line_("@ = @ + @;", .{ arithmetic.destination, arithmetic.left, arithmetic.right }),
                    .subtract => try self.line_("@ = @ - @;", .{ arithmetic.destination, arithmetic.left, arithmetic.right }),
                    .multiply => try self.line_("@ = @ * @;", .{ arithmetic.destination, arithmetic.left, arithmetic.right }),
                    .divide => try self.line_("if (@ == 0) { double t; em_float_arithmetic(@, @, @, &t, @); EM_FAIL; } @ = @ / @;", .{ arithmetic.right, op, arithmetic.left, arithmetic.right, site, arithmetic.destination, arithmetic.left, arithmetic.right }),
                    .floor_divide, .remainder, .power => try self.line_("{ double t; if (em_float_arithmetic(@, @, @, &t, @)) EM_FAIL; @ = t; }", .{ op, arithmetic.left, arithmetic.right, site, arithmetic.destination }),
                }
            },
            .negate_int => |negation| try self.line_("if (@ == INT64_MIN) { int64_t t; em_negate(@, &t, @); EM_FAIL; } @ = -@;", .{ negation.operand, negation.operand, siteName(&site_buffer, negation.site), negation.destination, negation.operand }),
            .negate_float => |negation| try self.line_("@ = -@;", .{ negation.destination, negation.operand }),
            .not => |negation| try self.line_("@ = !@;", .{ negation.destination, negation.operand }),
            .widen => |widening| try self.line_("@ = (double)@;", .{ widening.destination, widening.operand }),
            .compare => |comparison| try self.compare(comparison),
            .call => |called| try self.call(called),
            .write => |write| switch (write) {
                .text => |text| {
                    try self.out.writeAll("    em_write_text(");
                    try writeString(self.out, text);
                    try self.out.print(", {d});\n", .{text.len});
                },
                .int => |value| try self.line_("em_write_int(@);", .{value}),
                .float => |value| try self.line_("em_write_float(@);", .{value}),
                .bool => |value| try self.line_("em_write_bool(@);", .{value}),
                .string => |value| try self.line_("em_write_string(@);", .{value}),
                .value => |value| {
                    try self.out.writeAll("    em_write_value(");
                    try self.emValue(value);
                    try self.out.writeAll(");\n");
                },
            },
            .list_new => |built| {
                try self.out.writeAll("    {");
                try self.valueArray(built.items);
                try self.out.print(" em_list *t = em_list_new({s}, ", .{kindName(built.element)});
                try self.arrayArguments(built.items.len);
                try self.out.writeAll(");");
                try self.takeInto(built.destination);
                try self.out.writeAll(" }\n");
            },
            .list_count => |counted| try self.line_("@ = em_list_count(@);", .{ counted.destination, counted.list }),
            .list_get => |got| {
                try self.line_("{ em_value r; if (em_list_get(@, @, &r, @)) EM_FAIL;", .{ got.list, got.position, siteName(&site_buffer, got.site) });
                try self.storeResult(got.destination, got.element);
                try self.out.writeAll(" }\n");
            },
            .list_set => |set| {
                try self.out.writeAll("    if (em_list_set(&");
                try self.place(set.target);
                try self.out.writeAll(", ");
                try self.operand(set.position);
                try self.out.writeAll(", ");
                try self.emValue(set.value);
                try self.out.print(", {s})) EM_FAIL;\n", .{siteName(&site_buffer, set.site)});
            },
            .list_mutate => |changed| {
                try self.out.writeAll("    { em_value r;");
                try self.valueArray(changed.arguments);
                try self.out.writeAll(" if (em_list_mutate(&");
                try self.place(changed.target);
                try self.out.print(", {d}, ", .{changed.method});
                try self.arrayArguments(changed.arguments.len);
                try self.out.print(", {s}, &r, {s})) EM_FAIL;", .{ kindName(changed.result), siteName(&site_buffer, changed.site) });
                try self.storeResult(changed.destination, changed.result);
                try self.out.writeAll(" }\n");
            },
            .concat => |joined| {
                try self.line_("{ em_text *t = em_concat(@, @);", .{ joined.left, joined.right });
                try self.takeInto(joined.destination);
                try self.out.writeAll(" }\n");
            },
            .format => |built| {
                try self.out.writeAll("    { em_builder *b = em_builder_new();\n");
                for (built.parts) |part| switch (part) {
                    .text => |text| {
                        try self.out.writeAll("    em_builder_text(b, ");
                        try writeString(self.out, text);
                        try self.out.print(", {d});\n", .{text.len});
                    },
                    .int => |value| try self.line_("em_builder_int(b, @);", .{value}),
                    .float => |value| try self.line_("em_builder_float(b, @);", .{value}),
                    .bool => |value| try self.line_("em_builder_bool(b, @);", .{value}),
                    .string => |value| try self.line_("em_builder_string(b, @);", .{value}),
                    .value => |value| {
                        try self.out.writeAll("    em_builder_value(b, ");
                        try self.emValue(value);
                        try self.out.writeAll(");\n");
                    },
                };
                try self.out.writeAll("    em_text *t = em_builder_finish(b);");
                try self.takeInto(built.destination);
                try self.out.writeAll(" }\n");
            },
            .string_count => |counted| try self.line_("@ = em_string_count(@);", .{ counted.destination, counted.operand }),
            .string_index => |indexed| {
                try self.line_("{ em_text *t = 0; if (em_string_index(@, @, &t, @)) EM_FAIL;", .{ indexed.operand, indexed.position, siteName(&site_buffer, indexed.site) });
                try self.takeInto(indexed.destination);
                try self.out.writeAll(" }\n");
            },
            .string_slice => |sliced| {
                const start: Ir.Operand = sliced.start orelse .{ .int = 0 };
                const end: Ir.Operand = sliced.end orelse .{ .int = 0 };
                try self.line_("{ em_text *t = 0; if (em_string_slice(@, @, @, @, @, @, &t, @)) EM_FAIL;", .{
                    sliced.operand,
                    if (sliced.start != null) "true" else "false",
                    start,
                    if (sliced.end != null) "true" else "false",
                    end,
                    if (sliced.inclusive) "true" else "false",
                    siteName(&site_buffer, sliced.site),
                });
                try self.takeInto(sliced.destination);
                try self.out.writeAll(" }\n");
            },
            .native => |native| try self.nativeCall(native, siteName(&site_buffer, native.site)),
        }
    }

    /// A value as the runtime's `em_value`, for a native.
    fn emValue(self: *FunctionEmitter, typed: Ir.Typed) Writer.Error!void {
        try self.out.print("(em_value){{ {s}, {{ .{s} = ", .{ kindName(typed.type), fieldName(typed.type) });
        try self.operand(typed.operand);
        try self.out.writeAll(" } }");
    }

    fn nativeCall(self: *FunctionEmitter, native: anytype, site: []const u8) Writer.Error!void {
        const out = self.out;
        try out.writeAll("    { em_value r;");
        try self.valueArray(native.arguments);
        try out.print(" if (em_native({d}, {d}, ", .{ native.family, native.method });
        try self.emValue(native.receiver);
        if (native.arguments.len != 0) try out.print(", a, {d}", .{native.arguments.len}) else try out.writeAll(", 0, 0");
        try out.print(", {s}, &r, {s})) EM_FAIL;", .{ kindName(native.result), site });
        try self.storeResult(native.destination, native.result);
        try out.writeAll(" }\n");
    }

    /// Stores `r`, an `em_value` of `type_` the runtime gave, into
    /// `destination`, or releases it when nothing keeps it.
    fn storeResult(self: *FunctionEmitter, destination: ?Ir.Place, type_: Ir.Type) Writer.Error!void {
        const out = self.out;
        if (type_ == .nothing) return;
        if (destination) |into| {
            if (type_.counted()) {
                try out.print(" {s}t = r.as.{s};", .{ cType(type_), fieldName(type_) });
                try self.takeInto(into);
            } else {
                try out.writeAll(" ");
                try self.place(into);
                try out.print(" = r.as.{s};", .{fieldName(type_)});
            }
        } else if (type_.counted()) try out.print(" {s}(r.as.{s});", .{ releaseName(type_), fieldName(type_) });
    }

    /// `em_value a[] = { ... };`, or nothing for no values.
    fn valueArray(self: *FunctionEmitter, values: []const Ir.Typed) Writer.Error!void {
        if (values.len == 0) return;
        try self.out.writeAll(" em_value a[] = { ");
        for (values, 0..) |one, position| {
            if (position != 0) try self.out.writeAll(", ");
            try self.emValue(one);
        }
        try self.out.writeAll(" };");
    }

    fn arrayArguments(self: *FunctionEmitter, count: usize) Writer.Error!void {
        if (count != 0) try self.out.print("a, {d}", .{count}) else try self.out.writeAll("0, 0");
    }

    fn compare(self: *FunctionEmitter, comparison: anytype) Writer.Error!void {
        const symbol = switch (comparison.operator) {
            .equal => "==",
            .not_equal => "!=",
            .less => "<",
            .less_equal => "<=",
            .greater => ">",
            .greater_equal => ">=",
        };
        switch (comparison.kind) {
            // C's comparisons of doubles are IEEE's, as section 5.3 asks:
            // every comparison with NaN is false except `!=`.
            .int, .float, .bool => try self.line_("@ = @ @ @;", .{ comparison.destination, comparison.left, symbol, comparison.right }),
            .list => {
                try self.out.writeAll("    ");
                try self.place(comparison.destination);
                try self.out.writeAll(if (comparison.operator == .equal) " = em_equal_values(" else " = !em_equal_values(");
                try self.emValue(.{ .operand = comparison.left, .type = .list });
                try self.out.writeAll(", ");
                try self.emValue(.{ .operand = comparison.right, .type = .list });
                try self.out.writeAll(");\n");
            },
            // Section 9.2: by the code points of the normalized forms.
            .string => switch (comparison.operator) {
                .equal => try self.line_("@ = em_equal_strings(@, @);", .{ comparison.destination, comparison.left, comparison.right }),
                .not_equal => try self.line_("@ = !em_equal_strings(@, @);", .{ comparison.destination, comparison.left, comparison.right }),
                else => try self.line_("@ = em_compare_strings(@, @) @ 0;", .{ comparison.destination, comparison.left, comparison.right, symbol }),
            },
            // An exact comparison from the runtime: -1, 0 or 1, or 2 when
            // the `Float` is NaN, which only `!=` holds for.
            .int_float, .float_int => {
                const unordered = if (comparison.operator == .not_equal) "true" else "false";
                // A `Float` on the left swaps the operands and the result's
                // sign; `-2` is the swapped unordered result.
                if (comparison.kind == .int_float) {
                    try self.line_("{ int c = em_compare_int_float(@, @); @ = c == 2 ? @ : (c @ 0); }", .{ comparison.left, comparison.right, comparison.destination, unordered, symbol });
                } else {
                    try self.line_("{ int c = -em_compare_int_float(@, @); @ = c == -2 ? @ : (c @ 0); }", .{ comparison.right, comparison.left, comparison.destination, unordered, symbol });
                }
            },
        }
    }

    /// A call, its result in `t` and then stored: a string result is a new
    /// reference, which its destination takes over or which is released.
    fn call(self: *FunctionEmitter, called: anytype) Writer.Error!void {
        const out = self.out;
        const callee = self.program.functions[called.function];
        if (callee.result != .nothing) {
            try out.print("    {{ {s} t = 0;", .{cType(callee.result)});
        } else try out.writeAll("    {");
        try out.print(" if (em_function_{d}(", .{called.function});
        for (called.arguments, 0..) |argument, position| {
            if (position != 0) try out.writeAll(", ");
            try self.operand(argument);
        }
        if (callee.result != .nothing) {
            if (called.arguments.len != 0) try out.writeAll(", ");
            try out.writeAll("&t");
        }
        try out.print(")) {{ em_trace(&em_frame_{d}); EM_FAIL; }}", .{called.site});
        if (called.destination) |destination| {
            if (callee.result.counted()) {
                try self.takeInto(destination);
            } else {
                try out.writeAll(" ");
                try self.place(destination);
                try out.writeAll(" = t;");
            }
        } else if (callee.result.counted()) try out.print(" {s}(t);", .{releaseName(callee.result)});
        try out.writeAll(" }\n");
    }

    fn terminator(self: *FunctionEmitter, end: Ir.Terminator) Writer.Error!void {
        const out = self.out;
        switch (end) {
            .jump => |target| try out.print("    goto em_block_{d};\n", .{target}),
            .branch => |branch| {
                try out.writeAll("    if (");
                try self.operand(branch.condition);
                try out.print(") goto em_block_{d}; else goto em_block_{d};\n", .{ branch.then, branch.otherwise });
            },
            // The result is the caller's: a string is retained for it, since
            // the exit releases the local it came from.
            .@"return" => |returned_value| {
                if (returned_value) |returned| {
                    try out.writeAll("    *em_result = ");
                    try self.operand(returned);
                    try out.writeAll(";\n");
                    if (self.function.result.counted()) try out.print("    {s}(*em_result);\n", .{retainName(self.function.result)});
                }
                try out.writeAll("    goto em_exit;\n");
            },
        }
    }
};

fn operatorName(operator: @import("runtime").Operations.Arithmetic) []const u8 {
    return switch (operator) {
        .add => "EM_ADD",
        .subtract => "EM_SUBTRACT",
        .multiply => "EM_MULTIPLY",
        .divide => "EM_DIVIDE",
        .floor_divide => "EM_FLOOR_DIVIDE",
        .remainder => "EM_REMAINDER",
        .power => "EM_POWER",
    };
}
